import { expect, test } from '@playwright/test'
import { login, PASSWORD, signup, uniqueEmail } from './helpers'

test('owner configures tables, menu and staff; a cashier gets a restricted workspace', async ({ page, browser }) => {
  await signup(page)
  const nav = page.getByRole('navigation', { name: 'Main' })

  await nav.getByRole('link', { name: 'Tables & QR' }).click()
  await page.getByRole('button', { name: 'New table' }).click()
  let dialog = page.getByRole('dialog', { name: 'New table' })
  await dialog.getByLabel('Name').fill('T1')
  await dialog.getByLabel('Area').fill('Terrace')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('cell', { name: 'T1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'QR link' }).click()
  await expect(page.getByTestId('qr-url')).toContainText('/qr/')
  await page.getByRole('dialog', { name: /QR ordering/ }).getByRole('button', { name: 'Close' }).click()

  await nav.getByRole('link', { name: 'Menu' }).click()
  await page.getByRole('button', { name: 'New item' }).click()
  dialog = page.getByRole('dialog', { name: 'New menu item' })
  await dialog.getByLabel('Name', { exact: true }).fill('Masala Dosa')
  await dialog.getByLabel('Price (₹)', { exact: true }).fill('120')
  await dialog.getByLabel('Category').selectOption({ label: 'Main Course' })
  await expect(dialog.getByLabel('Tax group')).toHaveValue(/.+/)
  await dialog.getByLabel('Tax group').selectOption({ label: 'GST 5%' })
  await dialog.getByRole('button', { name: 'Save item' }).click()
  const dosaRow = page.getByRole('row').filter({ hasText: 'Masala Dosa' })
  await expect(dosaRow).toContainText('₹120.00')

  const chaasRow = page.getByRole('row').filter({ hasText: 'Masala Chaas' })
  await chaasRow.getByLabel('Available').click()
  await expect(chaasRow.getByLabel('Unavailable')).not.toBeChecked()

  await nav.getByRole('link', { name: 'POS' }).click()
  await page.getByRole('button', { name: /^Table T1/ }).click()
  await expect(page.getByRole('heading', { name: /Dine-in · Table T1/ })).toBeVisible()
  const menu = page.getByRole('region', { name: 'Menu items' })
  await expect(menu.getByRole('button', { name: /Masala Chaas/ })).toBeDisabled()
  await menu.getByRole('button', { name: /Masala Dosa/ }).click()
  await page.getByRole('button', { name: 'Send KOT' }).click()
  await expect(page.getByTestId('order-total')).toHaveText('₹126.00')
  await page.getByRole('link', { name: 'Back to POS' }).click()
  await expect(page.getByRole('button', { name: /^Table T1/ })).toContainText('₹126.00')

  const cashierEmail = uniqueEmail('cashier')
  await nav.getByRole('link', { name: 'Staff' }).click()
  await page.getByRole('button', { name: 'Add staff' }).click()
  dialog = page.getByRole('dialog', { name: 'Add staff' })
  await dialog.getByLabel('Name').fill('Ravi Cashier')
  await dialog.getByLabel('Email').fill(cashierEmail)
  await dialog.getByLabel('Temporary password').fill(PASSWORD)
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('row').filter({ hasText: cashierEmail })).toContainText('Cashier · Main Outlet')

  const cashierContext = await browser.newContext()
  const cashier = await cashierContext.newPage()
  await login(cashier, cashierEmail)
  await expect(cashier).toHaveURL(/\/pos$/)
  const cashierNav = cashier.getByRole('navigation', { name: 'Main' })
  await expect(cashierNav.getByRole('link', { name: 'Cash register' })).toBeVisible()
  await expect(cashierNav.getByRole('link', { name: 'Staff' })).toHaveCount(0)
  await expect(cashierNav.getByRole('link', { name: 'Settings' })).toHaveCount(0)
  await expect(cashier.getByRole('button', { name: /^Table T1/ })).toContainText('₹126.00')
  await cashierContext.close()
})
